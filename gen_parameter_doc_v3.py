def shade(cell, c):
    cell._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:fill="{c}"/>'))

def heading(text, level=1):
    h = doc.add_heading(text, level=level)
    for r in h.runs:
        r.font.name = '微软雅黑'; r.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')

def para(text, bold=False, size=10.5, sa=4, sb=0):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(sa); p.paragraph_format.space_before = Pt(sb)
    run = p.add_run(text); run.font.name = '微软雅黑'; run.font.size = Pt(size); run.bold = bold
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    return p

def bullet(text, level=0):
    p = doc.add_paragraph(style='List Bullet'); p.paragraph_format.space_after = Pt(2)
    if level > 0: p.paragraph_format.left_indent = Cm(1.2 * (level + 1))
    run = p.add_run(text); run.font.name = '微软雅黑'; run.font.size = Pt(10.5)
    run.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')

def make_tbl(headers, data, cw=None):
    t = doc.add_table(rows=0, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.style = 'Table Grid'
    for is_hdr, row_data in [(True, headers)] + [(False, d) for d in data]:
        row = t.add_row()
        for i, txt in enumerate(row_data):
            cell = row.cells[i]; cell.text = ''
            p = cell.paragraphs[0]; p.paragraph_format.space_after = Pt(2); p.paragraph_format.space_before = Pt(2)
            run = p.add_run(str(txt)); run.font.name = '微软雅黑'; run.font.size = Pt(9.5)
            run.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
            if is_hdr: run.bold = True; shade(cell, "D9E2F3")
    if cw:
        for i, w in enumerate(cw):
            for row in t.rows: row.cells[i].width = Cm(w)
    return t

def param_table(title, items):
    """序号 | 功能项 | 技术参数要求"""
    tbl = doc.add_table(rows=0, cols=3); tbl.alignment = WD_TABLE_ALIGNMENT.CENTER; tbl.style = 'Table Grid'
    for is_hdr, row_data in [(True, ['序号', '功能项', '技术参数要求'])] + [(False, it) for it in items]:
        row = tbl.add_row()
        for i, txt in enumerate(row_data):
            cell = row.cells[i]; cell.text = ''
            p = cell.paragraphs[0]; p.paragraph_format.space_after = Pt(1); p.paragraph_format.space_before = Pt(1)
            run = p.add_run(str(txt)); run.font.name = '微软雅黑'; run.font.size = Pt(9)
            run.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
            if is_hdr: run.bold = True; shade(cell, "D9E2F3")
    for i, w in enumerate([1.5, 3.2, 12.5]):
        for row in tbl.rows: row.cells[i].width = Cm(w)

